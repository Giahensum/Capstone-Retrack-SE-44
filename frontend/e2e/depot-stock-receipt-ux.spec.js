import { test, expect } from '@playwright/test';
import fs from 'node:fs';
import { randomUUID } from 'node:crypto';

test('Chủ kho sửa phiếu nháp, chống ghi đè và nhập kho một bước trên desktop/mobile', async ({ page, request }) => {
  test.skip(!process.env.E2E_FINISH_FIXTURE || !process.env.E2E_FINISH_PASSWORD, 'Cần fixture riêng trên Retrack_TV2_test.');
  test.setTimeout(120000);
  const f = JSON.parse(fs.readFileSync(process.env.E2E_FINISH_FIXTURE, 'utf8'));
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('/login');
  await page.getByLabel('Email', { exact: true }).fill(f.OwnerEmail);
  await page.getByLabel('Mật khẩu', { exact: true }).fill(process.env.E2E_FINISH_PASSWORD);
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click();
  await expect(page).not.toHaveURL(/\/login$/);
  const auth = await request.post('/api/auth/login', { data: { email: f.OwnerEmail, password: process.env.E2E_FINISH_PASSWORD } });
  const headers = { Authorization: `Bearer ${(await auth.json()).data.token}` };
  const endpoint = path => `/api/depot/${path}?depotId=${f.DepotId}`;
  const get = async path => (await (await request.get(endpoint(path), { headers })).json()).data;
  const unique = `Phiếu sửa ${randomUUID().slice(0, 8)}`;
  await page.goto('/depot/inventory?tab=receipts');
  await page.getByRole('button', { name: 'Lập phiếu nhập', exact: true }).click();
  let form = page.getByRole('dialog', { name: 'Lập phiếu nhập kho đa nguồn' });
  await form.getByLabel('Chứng từ / tham chiếu nguồn').fill(unique);
  await form.getByLabel('Số lượng (kg)').fill('100');
  await form.getByRole('combobox', { name: 'Vật liệu', exact: true }).selectOption('COPPER');
  await expect(form.getByRole('button', { name: 'Ghi nhận vào kho', exact: true })).toBeDisabled();
  const saving = page.waitForResponse(r => r.url().includes('/stock/receipts?') && r.request().method() === 'POST');
  await form.getByRole('button', { name: 'Lưu phiếu nháp', exact: true }).click();
  const draft = (await (await saving).json()).data;
  expect(draft.status).toBe('DRAFT');
  await expect(form).toHaveCount(0);
  const copperBefore = ((await get('inventory')).find(x => x.materialType === 'COPPER')?.receivedKg ?? 0);
  await page.reload();
  await page.getByRole('row').filter({ hasText: unique }).getByRole('button', { name: 'Chi tiết / duyệt' }).click();
  let review = page.getByRole('dialog', { name: /^Phiếu nhập:/ });
  await review.getByRole('button', { name: 'Sửa hàng thực nhận / phiếu nháp' }).click();
  form = page.getByRole('dialog', { name: 'Sửa phiếu nhập nháp' });
  await expect(form.getByRole('combobox', { name: 'Nguồn hàng', exact: true })).toBeDisabled();
  await form.getByLabel('Số lượng (kg)').fill('200');
  await form.getByRole('combobox', { name: 'Vật liệu', exact: true }).selectOption('PET');
  await form.getByRole('button', { name: 'Thêm dòng hàng', exact: true }).click();
  const second = form.locator('section').filter({ has: page.getByRole('heading', { name: 'Dòng 2', exact: true }) });
  await second.getByRole('combobox', { name: 'Nhóm hàng', exact: true }).selectOption('REUSABLE');
  await second.getByLabel('Tên đồ / hãng / model').fill('Tivi kiểm thử sửa nháp');
  await second.getByLabel('Số lượng (cái)').fill('2');
  await second.getByLabel('Tình trạng / lỗi đã biết / serial nếu có').fill('Đã kiểm tra hoạt động');
  for (const width of [390, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    const bounds = await form.boundingBox(); expect(bounds.x).toBeGreaterThanOrEqual(0); expect(bounds.x + bounds.width).toBeLessThanOrEqual(width);
    await page.screenshot({ path: test.info().outputPath(`sua-phieu-nhap-${width}.png`), fullPage: true });
  }
  await form.getByRole('button', { name: 'Lưu thay đổi phiếu nháp', exact: true }).click();
  await expect(form).toHaveCount(0);
  const updated = await get(`stock/receipts/${draft.id}`);
  expect(updated.lines.map(x => x.quantity)).toEqual([200, 2]);
  expect(updated.lines[0].materialType).toBe('PET');
  expect(updated.status).toBe('DRAFT');
  const stale = await request.put(endpoint(`stock/receipts/${draft.id}/draft`), { headers, data: {
    expectedRevision: draft.revision, reference: unique, purchaseCost: 0, costsConfirmed: false, lines: draft.lines, expenses: [] } });
  expect(stale.status()).toBe(409);
  await page.reload();
  await page.getByRole('row').filter({ hasText: unique }).getByRole('button', { name: 'Chi tiết / duyệt' }).click();
  review = page.getByRole('dialog', { name: /^Phiếu nhập:/ });
  await expect(review).toContainText('Nhựa PET · 200 kg');
  await expect(review).toContainText('Tivi kiểm thử sửa nháp · 2 cái');
  await review.getByRole('button', { name: 'Xác nhận hàng thực nhận và ghi sổ' }).click();
  await expect(review).toHaveCount(0);
  expect((await get(`stock/receipts/${draft.id}`)).status).toBe('POSTED');
  const forbidden = await request.put(endpoint(`stock/receipts/${draft.id}/draft`), { headers, data: {
    expectedRevision: updated.revision, reference: unique, purchaseCost: 0, costsConfirmed: false, lines: updated.lines, expenses: [] } });
  expect(forbidden.status()).toBe(409);
  await page.getByRole('button', { name: 'Lập phiếu nhập', exact: true }).click();
  form = page.getByRole('dialog', { name: 'Lập phiếu nhập kho đa nguồn' });
  await form.getByLabel('Chứng từ / tham chiếu nguồn').fill(`Ghi nhận nhanh ${unique}`);
  await form.getByRole('combobox', { name: 'Vật liệu', exact: true }).selectOption('COPPER');
  await form.getByLabel('Số lượng (kg)').fill('33');
  await form.getByRole('checkbox', { name: /Tôi đã kiểm tra hàng thực nhận/ }).check();
  const posting = page.waitForResponse(r => r.url().includes('/stock/receipts?') && r.request().method() === 'POST');
  await form.getByRole('button', { name: 'Ghi nhận vào kho', exact: true }).click();
  const postedResponse = await posting;
  expect(postedResponse.status()).toBe(200);
  const posted = (await postedResponse.json()).data;
  expect(posted.status).toBe('POSTED');
  await expect(form).toHaveCount(0);
  const replay = await request.post(endpoint('stock/receipts'), { headers, data: postedResponse.request().postDataJSON() });
  expect(replay.status()).toBe(200);
  await page.reload();
  expect((await get('inventory')).find(x => x.materialType === 'COPPER').receivedKg).toBe(copperBefore + 33);
  await page.getByRole('row').filter({ hasText: `Ghi nhận nhanh ${unique}` }).getByRole('button', { name: 'Chi tiết / duyệt' }).click();
  await expect(page.getByRole('dialog').getByRole('button', { name: 'Sửa hàng thực nhận / phiếu nháp' })).toHaveCount(0);
  expect(errors).toEqual([]);
});
