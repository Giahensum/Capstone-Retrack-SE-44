import { test, expect } from '@playwright/test';
test('Depot khảo sát, trả giá và lập phiếu đúng giá trọn lô qua API thật', async ({ page }) => {
  test.skip(!process.env.E2E_STOCK_EMAIL || !process.env.E2E_STOCK_PASSWORD, 'Cần fixture đầu ra contract Seller riêng.');
  test.setTimeout(90000);
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/login'); await page.getByLabel('Email', { exact: true }).fill(process.env.E2E_STOCK_EMAIL);
  await page.getByLabel('Mật khẩu', { exact: true }).fill(process.env.E2E_STOCK_PASSWORD);
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click(); await expect(page).toHaveURL(/\/depot/, { timeout: 20000 });
  await page.goto('/depot/liquidations');
  const open = async title => { await page.getByRole('article').filter({ hasText: title }).getByRole('button', { name: 'Xem lô và điều kiện' }).click(); return page.getByRole('dialog', { name: title, exact: true }); };
  let detail = await open('Lô khảo sát UI fixture');
  await expect(detail).toContainText('Đăng ký khảo sát để xem');
  await detail.getByRole('checkbox').check(); await detail.getByRole('button', { name: 'Đăng ký khảo sát', exact: true }).click();
  await expect(detail).toContainText('Địa chỉ khảo sát fixture');
  await detail.getByRole('checkbox').check(); await detail.getByRole('button', { name: 'Xác nhận đã khảo sát / hiểu hiện trạng' }).click();
  await expect(detail).toContainText('Kho đã đăng ký và tự xác nhận hiện trạng.');
  await page.reload(); detail = await open('Lô khảo sát UI fixture'); await expect(detail).toContainText('Kho đã đăng ký và tự xác nhận hiện trạng.');
  await detail.getByLabel('Đóng', { exact: true }).click(); detail = await open('Lô trả giá UI fixture');
  await detail.getByRole('checkbox').check(); await detail.getByRole('button', { name: 'Xác nhận đã khảo sát / hiểu hiện trạng' }).click();
  await detail.getByLabel('Tổng tiền bạn muốn trả (đ)').fill('10000000');
  await detail.getByRole('checkbox').check(); await detail.getByRole('button', { name: 'Xác nhận trả giá cả lô' }).click();
  await expect(detail).toContainText('Bạn đang giữ mức giá cao nhất.');
  await page.reload(); detail = await open('Lô trả giá UI fixture'); await expect(detail).toContainText('Bạn đang giữ mức giá cao nhất.');
  await detail.getByLabel('Đóng', { exact: true }).click(); detail = await open('Lô đã trúng UI fixture');
  await detail.getByRole('button', { name: 'Xem thỏa thuận lô trúng và giao nhận' }).click();
  const agreement = page.getByRole('dialog', { name: 'Thỏa thuận mua lô trúng', exact: true });
  await agreement.getByRole('checkbox').check(); await agreement.getByRole('button', { name: 'Xác nhận đã nhận đủ hàng về kho' }).click();
  await agreement.getByRole('button', { name: 'Lập phiếu nhập từ lô trúng' }).click();
  const form = page.getByRole('dialog', { name: 'Lập phiếu nhập kho đa nguồn' });
  await expect(form.getByLabel('Giá mua cả lô / giá trị tồn đầu kỳ (đ)')).toHaveValue('10000000');
  await expect(form.getByLabel('Giá mua cả lô / giá trị tồn đầu kỳ (đ)')).toHaveAttribute('readonly', '');
  await form.getByLabel('Số lượng (kg)').fill('1000'); await form.getByRole('button', { name: 'Lưu phiếu nháp' }).click();
  await expect(form).toHaveCount(0); await expect(agreement).toContainText('DRAFT');
  await expect(agreement.getByRole('button', { name: 'Lập phiếu nhập từ lô trúng' })).toHaveCount(0);
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(agreement).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: test.info().outputPath('lo-lon-mobile.png'), fullPage: true });
  expect(errors).toEqual([]);
});
