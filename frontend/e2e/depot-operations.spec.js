import { test, expect } from '@playwright/test';
test('Owner đọc thông báo, theo dõi sự cố và xem lịch sử hiệu suất qua API thật', async ({ page }) => {
  test.skip(!process.env.E2E_STOCK_EMAIL || !process.env.E2E_STOCK_PASSWORD, 'Cần fixture thông báo/sự cố riêng.');
  await page.goto('/login'); await page.getByLabel('Email', { exact: true }).fill(process.env.E2E_STOCK_EMAIL);
  await page.getByLabel('Mật khẩu', { exact: true }).fill(process.env.E2E_STOCK_PASSWORD);
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click(); await expect(page).toHaveURL(/\/depot/, { timeout: 20_000 });
  await page.goto('/depot/notifications');
  const notice = page.getByRole('article').filter({ hasText: 'Sự cố vận chuyển UI fixture' }); await expect(notice).toBeVisible();
  await notice.getByRole('button', { name: 'Đánh dấu đã đọc' }).click();
  await expect(notice.getByRole('button', { name: 'Đánh dấu đã đọc' })).toHaveCount(0);
  await notice.getByRole('button', { name: 'Xem lô / nhật ký xử lý' }).click();
  await page.getByRole('button', { name: 'Theo dõi xử lý' }).click();
  const dialog = page.getByRole('dialog', { name: 'Theo dõi xử lý vận chuyển' });
  await dialog.getByLabel('Trạng thái theo dõi').selectOption('CONTACTING');
  await dialog.getByLabel('Nội dung đã phối hợp / hướng xử lý').fill('Owner đã liên hệ tài xế và nhà máy');
  await dialog.getByRole('button', { name: 'Lưu ghi chú xử lý' }).click();
  await expect(dialog.getByRole('article').filter({ hasText: 'Owner đã liên hệ tài xế và nhà máy' })).toBeVisible();
  await dialog.getByLabel('Đóng', { exact: true }).click();
  await page.reload(); await page.getByRole('button', { name: 'Theo dõi xử lý' }).click();
  await expect(page.getByRole('dialog', { name: 'Theo dõi xử lý vận chuyển' }).getByRole('article').filter({ hasText: 'Owner đã liên hệ tài xế và nhà máy' })).toBeVisible();
  await page.goto('/depot/staff/performance');
  const row = page.getByRole('row').filter({ hasText: 'DEPOT_EMPLOYEE UI fixture' });
  await row.getByRole('button', { name: 'Xem lịch sử' }).click();
  const history = page.getByRole('dialog', { name: /Lịch sử công việc/ }); await expect(history).toContainText('12 kg');
  await history.getByLabel('Đóng', { exact: true }).click();
  await page.locator('input[type=month]').fill('2020-01');
  await expect(page.getByText('Không có dữ liệu tháng này.', { exact: true })).toHaveCount(0);
  await row.getByRole('button', { name: 'Xem lịch sử' }).click();
  await expect(page.getByRole('dialog', { name: /Lịch sử công việc/ })).toContainText('Không có công việc hoàn thành');
});
