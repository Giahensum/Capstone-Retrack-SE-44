// Run from any directory with Node 22+: node scripts/upload-branding.cjs
// Secrets are read server-side only and never written into client configuration.
const fs = require('node:fs/promises');
const path = require('node:path');
const { createHash } = require('node:crypto');
const root = path.resolve(__dirname, '..');
const hash = (data) => createHash('sha256').update(data).digest('hex');

async function main() {
  const config = JSON.parse(await fs.readFile(path.join(root, 'backend/Retrack.API/appsettings.json'), 'utf8'));
  const cloud = process.env.Cloudinary__CloudName || config.Cloudinary?.CloudName;
  const key = process.env.Cloudinary__ApiKey || config.Cloudinary?.ApiKey;
  const secret = process.env.Cloudinary__ApiSecret || config.Cloudinary?.ApiSecret;
  if (!cloud || !key || !secret) throw new Error('Missing Cloudinary server configuration.');

  async function upload(relativePath, name) {
    const bytes = await fs.readFile(path.join(root, relativePath));
    // Content-addressed IDs avoid overwriting another branding revision.
    const params = {
      overwrite: 'false',
      public_id: `retrack/branding/${name}-${hash(bytes).slice(0, 16)}`,
      timestamp: String(Math.floor(Date.now() / 1000)),
    };
    const signed = Object.keys(params).sort().map((k) => `${k}=${params[k]}`).join('&');
    const body = new FormData();
    for (const [k, v] of Object.entries(params)) body.append(k, v);
    body.append('api_key', key);
    body.append('signature', hash(signed + secret));
    body.append('file', new Blob([bytes], { type: 'image/png' }), `${name}.png`);
    const response = await fetch(`https://api.cloudinary.com/v1_1/${encodeURIComponent(cloud)}/image/upload`, {
      method: 'POST', body, signal: AbortSignal.timeout(90000),
    });
    if (!response.ok) throw new Error(`Cloudinary upload failed (HTTP ${response.status}).`);
    const result = await response.json();
    const url = new URL(result.secure_url);
    if (url.protocol !== 'https:' || url.hostname !== 'res.cloudinary.com') throw new Error('Unexpected delivery URL.');
    const downloaded = await fetch(url, { signal: AbortSignal.timeout(60000) });
    if (!downloaded.ok || hash(Buffer.from(await downloaded.arrayBuffer())) !== hash(bytes)) {
      throw new Error('Cloud image verification failed; client config was not changed.');
    }
    return url.href;
  }

  const logoUrl = await upload('docs/.ai-context/UI-Driver/logo_nobg.png', 'logo');
  const iconUrl = await upload('mobile/assets/retrack-icon.png', 'android-icon');
  // Only publish URLs after both originals have been downloaded and verified.
  for (const dir of ['mobile/src/config', 'frontend/src/config']) {
    await fs.mkdir(path.join(root, dir), { recursive: true });
    await fs.writeFile(path.join(root, dir, 'branding.js'),
      `// Public Cloudinary delivery URL; generated by scripts/upload-branding.cjs.\nexport const LOGO_URL = ${JSON.stringify(logoUrl)};\n`);
  }
  const appPath = path.join(root, 'mobile/app.json');
  const app = JSON.parse(await fs.readFile(appPath, 'utf8'));
  app.expo.icon = iconUrl;
  app.expo.android.adaptiveIcon.foregroundImage = iconUrl;
  const splash = app.expo.plugins.find((p) => Array.isArray(p) && p[0] === 'expo-splash-screen');
  if (!splash) throw new Error('Splash plugin configuration missing.');
  splash[1].image = logoUrl;
  await fs.writeFile(appPath, JSON.stringify(app, null, 2) + '\n');
  console.log(JSON.stringify({ logoUrl, iconUrl, verified: 'SHA-256 matches local originals' }, null, 2));
}

main().catch((error) => {
  // Avoid dumping request objects or server credentials on upload failures.
  console.error(error.message);
  process.exitCode = 1;
});
